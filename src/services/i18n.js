/**
 * Direct translator function
 */
export const translate = (lang, key) => {
  const targetLang = DICTIONARY[lang] ? lang : 'en';
  return DICTIONARY[targetLang][key] || DICTIONARY.en[key] || key;
};

/**
 * Reactive React Hook for automatic localization across any component
 */
export function useTranslation() {
  const [settings, setSettings] = useState(getStoredSettings);

  useEffect(() => {
    const unsub = subscribeSettings((updated) => {
      setSettings(updated);
    });
    return unsub;
  }, []);

  const lang = settings.language || 'en';

  const t = useCallback((key) => {
    return translate(lang, key);
  }, [lang]);

  return {
    t,
    language: lang,
    settings
  };
}
